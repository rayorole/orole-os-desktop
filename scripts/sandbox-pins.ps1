<#
.SYNOPSIS
  Writes internal/sandbox/pins.go from the qemu-v* and guest-v* GitHub releases: each asset's SHA-256 (from
  the release's SHA256SUMS, which its workflow computed, cross-checked against GitHub's own asset digest) and
  size (from GitHub). Draft releases are read too (gh sees them with repository access); the pinned URLs only
  work for users once both releases are published. Review the diff before committing.
.EXAMPLE
  ./scripts/sandbox-pins.ps1 -QemuTag qemu-v20260811 -GuestTag guest-v0.1.0
#>
param(
  [Parameter(Mandatory)][string]$QemuTag,   # e.g. qemu-v20260811
  [Parameter(Mandatory)][string]$GuestTag   # e.g. guest-v0.1.0
)
$ErrorActionPreference = "Stop"
Set-Location (Split-Path $PSScriptRoot -Parent)
$repo = "rayorole/orole-os-desktop"

function Get-Assets([string]$tag) {
  $json = gh release view $tag --repo $repo --json assets,isDraft
  if ($LASTEXITCODE) { throw "cannot read release $tag" }
  $rel = $json | ConvertFrom-Json
  if ($rel.isDraft) { Write-Warning "$tag is a draft: users cannot download it until it is published" }
  $dir = Join-Path ([IO.Path]::GetTempPath()) "orole-pins-$tag"
  New-Item -ItemType Directory -Force $dir | Out-Null
  gh release download $tag --repo $repo --pattern SHA256SUMS --dir $dir --clobber
  if ($LASTEXITCODE) { throw "cannot download SHA256SUMS of $tag" }
  $sums = @{}
  foreach ($line in Get-Content (Join-Path $dir "SHA256SUMS")) {
    $parts = $line.Trim() -split '\s+'
    if ($parts.Count -ge 2) { $sums[$parts[-1].TrimStart('*')] = $parts[0].ToLower() }
  }
  $out = @{}
  foreach ($a in $rel.assets | Where-Object { $_.name -ne "SHA256SUMS" }) {
    if (-not $sums.ContainsKey($a.name)) { throw "${tag}: $($a.name) is not listed in SHA256SUMS" }
    $sha = $sums[$a.name]
    if ($sha -notmatch '^[0-9a-f]{64}$') { throw "${tag}: bad SHA-256 for $($a.name): $sha" }
    # GitHub hashes every uploaded asset itself: a mismatch means the upload is not what the workflow hashed.
    if ($a.digest -and $a.digest -ne "sha256:$sha") { throw "${tag}: $($a.name) is $($a.digest) on GitHub, SHA256SUMS says $sha" }
    $out[$a.name] = [pscustomobject]@{ Name = $a.name; Sha = $sha; Size = [int64]$a.size }
  }
  return $out
}

function Format-Asset($a) { "Asset{Name: `"$($a.Name)`", SHA256: `"$($a.Sha)`", Size: $($a.Size)}" }

if ($QemuTag -notmatch '^qemu-v\d+$') { throw "QemuTag must look like qemu-v20260811" }
if ($GuestTag -notmatch '^guest-v\d+\.\d+\.\d+$') { throw "GuestTag must look like guest-v0.1.0" }
$qemuVersion = $QemuTag -replace '^qemu-v', ''
$imageVersion = $GuestTag -replace '^guest-v', ''
$q = Get-Assets $QemuTag
$g = Get-Assets $GuestTag
$zipName = "qemu-$qemuVersion-win64.zip"
if (-not $q.ContainsKey($zipName)) { throw "$QemuTag has no $zipName" }
$image = foreach ($n in "vmlinuz", "initrd", "cmdline", "base.qcow2") {
  if (-not $g.ContainsKey($n)) { throw "$GuestTag has no $n" }
  "`t`t" + (Format-Asset $g[$n]) + ","
}
$go = @"
// Code generated by scripts/sandbox-pins.ps1 -QemuTag $QemuTag -GuestTag $GuestTag; DO NOT EDIT.

package sandbox

// DefaultPins is the QEMU build and guest image this Orole build downloads (GitHub releases of
// rayorole/orole-os-desktop, https://github.com/rayorole/orole-os-desktop/releases/download/<tag>/<name>).
// Every file is checked against these sizes and hashes before it is used.
var DefaultPins = Pins{
	QEMUVersion:  "$qemuVersion",
	QEMUTag:      "$QemuTag",
	QEMU:         $(Format-Asset $q[$zipName]),
	ImageVersion: "$imageVersion",
	ImageTag:     "$GuestTag",
	Image: []Asset{
$($image -join "`n")
	},
}
"@
[IO.File]::WriteAllText((Join-Path (Get-Location) "internal/sandbox/pins.go"), ($go -replace "`r`n", "`n") + "`n")
gofmt -s -w internal/sandbox/pins.go
if ($LASTEXITCODE) { throw "gofmt failed" }
Write-Host "wrote internal/sandbox/pins.go"
